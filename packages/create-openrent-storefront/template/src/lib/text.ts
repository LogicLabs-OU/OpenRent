export type TextKey = keyof (typeof TEXTS)['en'];
export const LANGS = Object.keys(TEXTS);

/** `t('nav.cart', { count: 2 })` in the given language, else English. */
export function translator(lang: string) {
  const own = (TEXTS as Record<string, Record<string, string>>)[lang] ?? TEXTS.en;
  return (key: TextKey, params: Record<string, string | number> = {}) => (own[key] ?? TEXTS.en[key]).replace(/\{(\w+)\}/g, (_m, k: string) => String(params[k] ?? `{${k}}`));
}
